// ============================================================================
// FIREBASE ENVIRONMENT - choose emulator vs. deployed project at build time.
// Values are compile-time constants: change them, then rebuild the app.
// ============================================================================

import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';

import '../firebase_options.dart';

/// Which Firebase backend the app talks to.
///
/// The local Emulator Suite is the default so `flutter run` keeps working
/// without any Firebase setup. Build against the deployed project with:
///
/// ```sh
/// flutter run --dart-define=USE_FIREBASE_EMULATOR=false
/// ```
abstract final class AppEnvironment {
  /// `true` (the default) uses the Emulator Suite; `false` uses the deployed
  /// project described by `lib/firebase_options.dart`.
  static const bool useFirebaseEmulator = bool.fromEnvironment(
    'USE_FIREBASE_EMULATOR',
    defaultValue: true,
  );

  /// Project id the emulators report. It only has to match the id passed to
  /// `firebase emulators:start` (see `firebase.json`), not a real project.
  static const String emulatorProjectId = String.fromEnvironment(
    'FIREBASE_EMULATOR_PROJECT_ID',
    defaultValue: 'demo-bserv',
  );

  /// Optional emulator host override. Empty means it is detected per platform.
  static const String _emulatorHostOverride = String.fromEnvironment(
    'FIREBASE_EMULATOR_HOST',
  );

  /// Auth emulator port; must match `firebase.json`.
  static const int authEmulatorPort = int.fromEnvironment(
    'FIREBASE_AUTH_EMULATOR_PORT',
    defaultValue: 9299,
  );

  /// Firestore emulator port; must match `firebase.json`.
  static const int firestoreEmulatorPort = int.fromEnvironment(
    'FIREBASE_FIRESTORE_EMULATOR_PORT',
    defaultValue: 8180,
  );

  /// Storage emulator port; must match `firebase.json`.
  static const int storageEmulatorPort = int.fromEnvironment(
    'FIREBASE_STORAGE_EMULATOR_PORT',
    defaultValue: 9298,
  );

  /// Host the emulators are reachable on from the running client.
  ///
  /// The Android emulator reaches the host machine through `10.0.2.2`; every
  /// other platform (including web) talks to loopback directly. Set
  /// `FIREBASE_EMULATOR_HOST` to override this, for example when running on a
  /// physical device that reaches the emulators over the local network.
  static String get emulatorHost {
    if (_emulatorHostOverride.isNotEmpty) return _emulatorHostOverride;
    return !kIsWeb && defaultTargetPlatform == TargetPlatform.android
        ? '10.0.2.2'
        : '127.0.0.1';
  }

  /// Options for the deployed project, resolved per platform by
  /// `lib/firebase_options.dart` (generated by `flutterfire configure`).
  static FirebaseOptions get deployedOptions =>
      DefaultFirebaseOptions.currentPlatform;

  /// Placeholder options that satisfy `Firebase.initializeApp` while the
  /// Emulator Suite provides the real behaviour.
  static const FirebaseOptions emulatorOptions = FirebaseOptions(
    apiKey: 'demo-api-key',
    appId: '1:1234567890:web:bserv-demo',
    messagingSenderId: '1234567890',
    projectId: emulatorProjectId,
    storageBucket: '$emulatorProjectId.appspot.com',
  );
}
